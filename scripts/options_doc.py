#!/usr/bin/env python3
"""Generate docs/OPTIONS.md from engine/MED_option.m31 (ROADMAP item 31).

    python3 scripts/options_doc.py            write docs/OPTIONS.md
    python3 scripts/options_doc.py --check    exit 1 when docs/OPTIONS.md is out of date

An option "acts" when its name or short name is read somewhere in engine/ or ui/ (a quoted string outside the
table and the completion data); every other option is accepted by `:set`, shows through `:set opt?` and is kept,
but changes nothing. The check is a text search, so it can only err towards "acts"; the table itself is the list.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP = {"MED_option.m31", "MED_complete_data.m31", "MED_expr.m31", "MED_autocmd.m31"}


def specs():
    text = open(os.path.join(ROOT, "engine", "MED_option.m31")).read()
    out = []
    for match in re.finditer(r'^\s+"([a-z0-9]+):([a-z0-9]*):(bool|num|str):([^"]*)",?\s*$', text, re.M):
        out.append(match.groups())
    return out


def source_text():
    parts = []
    for folder in ("engine", "ui"):
        base = os.path.join(ROOT, folder)
        for name in sorted(os.listdir(base)):
            if name.endswith(".m31") and name not in SKIP:
                parts.append(open(os.path.join(base, name)).read())
    return "\n".join(parts)


def render():
    code = source_text()
    rows = []
    acts = 0
    for name, short, kind, default in specs():
        used = ('"%s"' % name in code) or (short != "" and ('"%s"' % short in code))
        acts += 1 if used else 0
        shown = default if default != "" else "(empty)"
        rows.append("| `%s` | %s | %s | `%s` | %s |" % (name, short and "`%s`" % short or "", kind, shown.replace("|", "\\|"),
                                                        "acts" if used else "stored only"))
    head = ("# Options\n\nGenerated by `python3 scripts/options_doc.py` from `engine/MED_option.m31`; `tests/test_core.sh` fails "
            "when this file is out of date. Every option below is accepted by `:set` (`:set opt?`, `opt&`, `opt!`, `invopt`, "
            "`noopt`, `opt+=`, `opt-=`, `opt^=` as nvim has them) and keeps its value; **acts** means the editor reads it, "
            "**stored only** means it changes nothing yet.\n\n%d options, %d act, %d stored only.\n\n"
            "| option | short | kind | default | status |\n|---|---|---|---|---|\n" % (len(rows), acts, len(rows) - acts))
    return head + "\n".join(rows) + "\n"


def main():
    path = os.path.join(ROOT, "docs", "OPTIONS.md")
    text = render()
    if "--check" in sys.argv:
        current = open(path).read() if os.path.exists(path) else ""
        if current != text:
            print("docs/OPTIONS.md is out of date: run python3 scripts/options_doc.py")
            sys.exit(1)
        print("docs/OPTIONS.md is current")
        return
    with open(path, "w") as handle:
        handle.write(text)
    print("wrote %s" % path)


if __name__ == "__main__":
    main()
